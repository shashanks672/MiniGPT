import torch
import torch.nn as nn

from dataset import get_batch
from model import MiniGPT


# ============================================================
# Create model
# ============================================================

model = MiniGPT()


# ============================================================
# Loss function
# ============================================================

loss_function = nn.CrossEntropyLoss()


# ============================================================
# Optimizer
# ============================================================

optimizer = torch.optim.AdamW(
    model.parameters(),
    lr=0.001
)


# ============================================================
# Training configuration
# ============================================================

num_steps = 5000


# ============================================================
# Training loop
# ============================================================

for step in range(num_steps):

    # --------------------------------------------------------
    # Get a new training batch
    # --------------------------------------------------------

    x, y = get_batch()

    # --------------------------------------------------------
    # Forward pass
    # --------------------------------------------------------

    logits = model(x)

    # --------------------------------------------------------
    # Flatten logits
    # --------------------------------------------------------

    logits = logits.view(
        -1,
        model.lm_head.out_features
    )

    # --------------------------------------------------------
    # Flatten targets
    # --------------------------------------------------------

    y = y.view(-1)

    # --------------------------------------------------------
    # Calculate loss
    # --------------------------------------------------------

    loss = loss_function(
        logits,
        y
    )

    # --------------------------------------------------------
    # Clear old gradients
    # --------------------------------------------------------

    optimizer.zero_grad()

    # --------------------------------------------------------
    # Backward pass
    # --------------------------------------------------------

    loss.backward()

    # --------------------------------------------------------
    # Update model weights
    # --------------------------------------------------------

    optimizer.step()

    # --------------------------------------------------------
    # Print loss
    # --------------------------------------------------------

    if step % 100 == 0:

        print(
            f"Step {step}, Loss: {loss.item():.4f}"
        )


# ============================================================
# Save trained model
# ============================================================

torch.save(
    model.state_dict(),
    "minigpt.pth"
)

print("Model saved successfully!")